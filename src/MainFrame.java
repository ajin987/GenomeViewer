    //Sequence Wrapping
    private String wrapSequence(String seq, int lineLength) {
    StringBuilder sb = new StringBuilder();

    for (int i = 0; i < seq.length(); i += lineLength) {
        int end = Math.min(i + lineLength, seq.length());
        sb.append(seq.substring(i, end)).append("\n");
    }

    return sb.toString();
    }
    
    


